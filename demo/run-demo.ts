/**
 * Replays the CUS_001 demo call's tool sequence against the real API and
 * writes the exact requests/responses into demo/demo-transcript.md.
 *
 *   npm run demo
 */
import { readFileSync, writeFileSync } from "node:fs";
import type { AddressInfo } from "node:net";
import { createApp } from "../backend/server.ts";

delete process.env.TOOL_API_KEY;
const server = createApp();
await new Promise<void>((r) => server.listen(0, r));
const base = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
console.log = ((orig) => (...a: unknown[]) => { if (!String(a[0]).match(/^(GET|POST) /)) orig(...a); })(console.log);

const steps: Array<[string, string, string, unknown?]> = [
  ["get_customer", "GET", "/api/customers/CUS_001"],
  ["get_payment_status", "GET", "/api/customers/CUS_001/payment"],
  ["retry_payment", "POST", "/api/payments/CUS_001/retry", { customer_consent: true }],
  ["log_outcome", "POST", "/api/outcomes", {
    customer_id: "CUS_001",
    outcome: "payment_recovery_initiated",
    summary: "Customer confirmed funds are now available and consented to retry of ₹1,499. Retry initiated.",
  }],
];

await fetch(base + "/api/reset", { method: "POST" });
const md: string[] = [];
let n = 1;
for (const [tool, method, path, body] of steps) {
  const res = await fetch(base + path, {
    method,
    headers: { "content-type": "application/json" },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  const json = await res.json();
  console.log(`\n[${n}] ${tool}  ${method} ${path} -> ${res.status}`);
  if (body) console.log("request:", JSON.stringify(body));
  console.log("response:", JSON.stringify(json, null, 2));
  md.push(`### ${n++}. \`${tool}\` → \`${method} ${path}\` (${res.status})`, "");
  if (body) md.push("Request:", "```json", JSON.stringify(body, null, 2), "```", "");
  md.push("Response:", "```json", JSON.stringify(json, null, 2), "```", "");
}
const final = await (await fetch(base + "/api/customers/CUS_001/payment")).json() as any;
md.push("### Final state", "", "```text",
  `Customer : ${final.customer_id} (${final.name})`,
  `Amount   : ₹${final.amount_inr.toLocaleString("en-IN")}`,
  `Reason   : ${final.failure_reason}`,
  `Status   : ${final.status} (attempt ${final.attempts})`,
  `Outcome  : payment_recovery_initiated`, "```");
server.close();

const file = new URL("./demo-transcript.md", import.meta.url);
writeFileSync(file, readFileSync(file, "utf8").replace(
  /<!-- AUTO:START -->[\s\S]*<!-- AUTO:END -->/,
  `<!-- AUTO:START -->\n_Generated by \`npm run demo\` on ${new Date().toISOString()}._\n\n${md.join("\n")}\n<!-- AUTO:END -->`,
));
console.log(`\nFinal: ${final.status}. Wrote demo/demo-transcript.md`);
